/* ============================================================
   「サイトのページ」の一覧を返します。
   ------------------------------------------------------------
   tools/ の各コマンドは、必ずこれを通してHTMLを数えてください。

   フォルダ直下には、ページ以外のHTMLが置かれることがあります。
   （例：Googleサーチコンソールの所有者確認ファイル google〇〇.html）
   これらは共通パーツを入れる対象でも、サイトマップに載せる対象でもないので、
   ここで一括して除外します。
   ============================================================ */
'use strict';
const fs = require('fs');

/* ページとして扱わないファイル */
const SKIP = [
  /^google[0-9a-f]{10,}\.html$/i   // Googleの所有者確認ファイル（消すと確認が外れます）
];

module.exports = function pages(root) {
  return fs.readdirSync(root)
    .filter(f => /\.html$/.test(f))
    .filter(f => !SKIP.some(re => re.test(f)));
};
